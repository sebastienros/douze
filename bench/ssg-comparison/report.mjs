// Aggregates the runs that bench.sh wrote (<out>/<generator>/<generator>.jsonl) into results.json and results.md.
// Usage: node report.mjs <out folder>
import fs from "node:fs";
import path from "node:path";

const outDir = process.argv[2] ?? ".work/out";
const order = ["douze", "hugo", "eleventy", "astro", "jekyll"];
const names = { douze: "Douze", hugo: "Hugo", eleventy: "Eleventy", astro: "Astro", jekyll: "Jekyll" };

const runs = [];
const versions = {};
for (const gen of order) {
  const file = path.join(outDir, gen, `${gen}.jsonl`);
  if (!fs.existsSync(file)) continue;
  for (const line of fs.readFileSync(file, "utf8").split("\n")) {
    if (line.trim()) runs.push(JSON.parse(line));
  }
  const v = path.join(outDir, gen, `${gen}.versions.txt`);
  if (fs.existsSync(v)) versions[gen] = fs.readFileSync(v, "utf8").trim();
}
const envFile = path.join(outDir, "environment.txt");
const environment = fs.existsSync(envFile) ? fs.readFileSync(envFile, "utf8").trim() : "";

const median = xs => {
  const s = [...xs].sort((a, b) => a - b);
  const m = s.length >> 1;
  return s.length % 2 ? s[m] : (s[m - 1] + s[m]) / 2;
};

const summary = [];
const keys = new Map();
for (const r of runs) {
  const key = `${r.generator}|${r.kind}|${r.size}`;
  if (!keys.has(key)) keys.set(key, []);
  keys.get(key).push(r);
}
for (const [key, rs] of keys) {
  const [generator, kind, size] = key.split("|");
  const ok = rs.every(r => r.ok);
  const secs = rs.map(r => r.seconds);
  summary.push({
    generator, kind, size: Number(size), ok,
    fastest: Math.min(...secs), median: median(secs), runs: secs,
    html: rs[0].html, posts: rs[0].posts,
  });
}

fs.writeFileSync("results.json", JSON.stringify({ environment, versions, summary, runs }, null, 2) + "\n");

const sizes = [...new Set(summary.map(s => s.size))].sort((a, b) => a - b);
const cell = s => (s ? (s.ok ? s.fastest.toFixed(3) : `${s.fastest.toFixed(3)} (failed)`) : "");
const cellMedian = s => (s ? s.median.toFixed(3) : "");
const rows = (kind, f) =>
  order
    .filter(g => summary.some(s => s.generator === g && s.kind === kind))
    .map(g => {
      const label = kind === "warm" ? `${names[g]} (rebuild, cache warm)` : names[g];
      return `| ${label} | ${sizes.map(n => f(summary.find(s => s.generator === g && s.kind === kind && s.size === n))).join(" | ")} |`;
    });
const header = `| Generator | ${sizes.join(" | ")} |\n|---|${sizes.map(() => "---:").join("|")}|`;
const pages = order
  .filter(g => summary.some(s => s.generator === g))
  .map(g => `| ${names[g]} | ${sizes.map(n => { const s = summary.find(x => x.generator === g && x.kind === "clean" && x.size === n); return s ? `${s.posts} / ${s.html}` : ""; }).join(" | ")} |`);

const md = `# Results

Seconds, lower is better. Wall clock of the build command inside the container, output and caches deleted before each
run. Generated by report.mjs from the runs in .work/out.

## Fastest of the runs

${header}
${rows("clean", cell).join("\n")}
${rows("warm", cell).join("\n")}

## Median of the runs

${header}
${rows("clean", cellMedian).join("\n")}
${rows("warm", cellMedian).join("\n")}

## Pages written (post pages / all HTML files)

${header}
${pages.join("\n")}

## Environment

\`\`\`
${environment}
\`\`\`

## Versions

${order.filter(g => versions[g]).map(g => `### ${names[g]}\n\n\`\`\`\n${versions[g]}\n\`\`\``).join("\n\n")}
`;
fs.writeFileSync("results.md", md);
