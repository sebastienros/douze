// Aggregates the docs-heavy runs (<out>/<generator>/<generator>.jsonl, written by bench-docs-heavy.sh) into
// results-docs-heavy.json and results-docs-heavy.md.
// Usage: node report-docs-heavy.mjs <out folder>
import fs from "node:fs";
import path from "node:path";

const outDir = process.argv[2] ?? ".work/docs-heavy/out";
const order = ["douze", "hugo", "eleventy", "astro", "jekyll"];
const names = { douze: "Douze", hugo: "Hugo", eleventy: "Eleventy", astro: "Astro", jekyll: "Jekyll" };
const warmNames = {
  douze: "Douze, disk cache",
  astro: "Astro, content layer cache",
  jekyll: "Jekyll, --incremental",
};

const runs = [];
const versions = {};
for (const gen of order) {
  const file = path.join(outDir, gen, `${gen}.jsonl`);
  if (!fs.existsSync(file)) continue;
  for (const line of fs.readFileSync(file, "utf8").split("\n")) if (line.trim()) runs.push(JSON.parse(line));
  const v = path.join(outDir, gen, `${gen}.versions.txt`);
  if (fs.existsSync(v)) versions[gen] = fs.readFileSync(v, "utf8").trim();
}
const envFile = path.join(outDir, "environment.txt");
const environment = fs.existsSync(envFile) ? fs.readFileSync(envFile, "utf8").trim() : "";

const median = xs => {
  const s = [...xs].sort((a, b) => a - b);
  const m = s.length >> 1;
  return s.length % 2 ? s[m] : (s[m - 1] + s[m]) / 2;
};

const groups = new Map();
for (const r of runs) {
  const key = `${r.generator}|${r.kind}|${r.size}`;
  if (!groups.has(key)) groups.set(key, []);
  groups.get(key).push(r);
}
const summary = [];
for (const [key, rs] of groups) {
  const [generator, kind, size] = key.split("|");
  const secs = rs.map(r => r.seconds);
  const med = rs.find(r => r.seconds === median(secs)) ?? rs[0];
  summary.push({
    generator, kind, size: Number(size), ok: rs.every(r => r.ok), timeout: rs.some(r => r.timeout),
    fastest: Math.min(...secs), median: median(secs), runs: secs,
    // CPU utilization: (user + sys) / wall, averaged over the runs
    cpu: rs.reduce((a, r) => a + r.cpu / r.seconds, 0) / rs.length,
    html: med.html, pages: med.pages, highlighted: med.highlighted, ids: med.ids,
  });
}

fs.writeFileSync("results-docs-heavy.json", JSON.stringify({ environment, versions, summary, runs }, null, 2) + "\n");

const sizes = [...new Set(summary.map(s => s.size))].sort((a, b) => a - b);
const find = (g, k, n) => summary.find(s => s.generator === g && s.kind === k && s.size === n);
const status = s => (s.timeout ? " (timed out)" : s.ok ? "" : " (failed)");
const table = (kind, f, label = g => names[g]) =>
  order
    .filter(g => summary.some(s => s.generator === g && s.kind === kind))
    .map(g => `| ${label(g)} | ${sizes.map(n => { const s = find(g, kind, n); return s ? f(s) : "not run"; }).join(" | ")} |`)
    .join("\n");
const header = `| Generator | ${sizes.join(" | ")} |\n|---|${sizes.map(() => "---:").join("|")}|`;

const md = `# Docs-heavy results

Seconds, lower is better. Wall clock of the build command inside the container, output and caches deleted before each
run. Generated by report-docs-heavy.mjs from the runs in .work/docs-heavy/out.

## Fastest of the runs

${header}
${table("clean", s => s.fastest.toFixed(3) + status(s))}

## Median of the runs

${header}
${table("clean", s => s.median.toFixed(3) + status(s))}

## Warm rebuilds, nothing changed (fastest, median)

${header}
${table("warm", s => `${s.fastest.toFixed(3)}, ${s.median.toFixed(3)}${status(s)}`, g => warmNames[g] ?? names[g])}

## CPU utilization of the clean builds ((user + sys) / wall, mean of the runs)

${header}
${table("clean", s => s.cpu.toFixed(2))}

## Checks (doc pages / pages with highlighted tokens / pages with h2 ids / all HTML files, median run)

${header}
${table("clean", s => `${s.pages} / ${s.highlighted} / ${s.ids} / ${s.html}`)}

## Environment

\`\`\`
${environment}
\`\`\`

## Versions

${order.filter(g => versions[g]).map(g => `### ${names[g]}\n\n\`\`\`\n${versions[g]}\n\`\`\``).join("\n\n")}
`;
fs.writeFileSync("results-docs-heavy.md", md);
